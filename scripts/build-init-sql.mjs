// Fallback path for the initial remote D1 bring-up when
// `wrangler d1 migrations apply` cannot resolve migrations_dir.
//
// Concatenates every drizzle/NNNN_*.sql into one file, strips Drizzle's
// `--> statement-breakpoint` markers, and appends INSERTs into wrangler's
// own `d1_migrations` bookkeeping table so that future
// `wrangler d1 migrations apply` runs treat these as already applied.
//
// Output: .wrangler-init.sql (gitignored). Apply with:
//   wrangler d1 execute caju-os-prod --remote --file=.wrangler-init.sql

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from './cf-config.mjs';

const dir = join(REPO_ROOT, 'drizzle');
const files = readdirSync(dir)
  .filter((f) => /^\d{4}_.*\.sql$/.test(f))
  .sort();

let sql = '-- Generated by scripts/build-init-sql.mjs. Do not edit.\n';
sql += 'CREATE TABLE IF NOT EXISTS d1_migrations (\n';
sql += '  id INTEGER PRIMARY KEY AUTOINCREMENT,\n';
sql += '  name TEXT UNIQUE,\n';
sql += "  applied_at TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now'))\n";
sql += ');\n\n';

for (const file of files) {
  const body = readFileSync(join(dir, file), 'utf8').replace(/-->\s*statement-breakpoint/g, '');
  sql += `-- ${file}\n${body.trim()}\n\n`;
}

sql += '-- bookkeeping so `wrangler d1 migrations apply` sees these as done\n';
for (const file of files) {
  sql += `INSERT OR IGNORE INTO d1_migrations (name) VALUES ('${file}');\n`;
}

const outPath = join(REPO_ROOT, '.wrangler-init.sql');
writeFileSync(outPath, sql);
console.log(`Wrote ${outPath} (${files.length} migrations).`);
