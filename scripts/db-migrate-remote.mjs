// Applies pending Drizzle migrations to the REMOTE Cloudflare D1 database.
//
// Wrangler 4.92 does not honour `migrations_dir` from a `-c` JSON config, so
// this drives `d1 execute` directly. It reads the d1_migrations bookkeeping
// table first and emits only the files that are not recorded there — running it
// twice is a no-op rather than a pile of "table already exists" errors.

import { readdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { loadCfConfig, REPO_ROOT } from './cf-config.mjs';

const cfg = loadCfConfig();
const migrationsDir = join(REPO_ROOT, 'drizzle');
const pendingPath = join(REPO_ROOT, '.wrangler-pending.sql');

// spawnSync with shell:true (needed for npx on Windows) does not quote args,
// so anything containing spaces — the SQL — has to be quoted explicitly.
const useShell = process.platform === 'win32';
const wrangler = (args, capture) =>
  spawnSync('npx', ['wrangler', ...args].map((a) => (useShell && /\s/.test(a) ? `"${a}"` : a)), {
    cwd: REPO_ROOT,
    shell: useShell,
    encoding: 'utf8',
    stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit',
  });

const all = readdirSync(migrationsDir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();

// Which ones has the database already seen?
let applied = new Set();
const probe = wrangler(
  ['d1', 'execute', cfg.d1_database_name, '--remote', '--json', '--command', 'SELECT name FROM d1_migrations;'],
  true,
);
if (probe.status === 0) {
  try {
    const rows = JSON.parse(probe.stdout)[0]?.results ?? [];
    applied = new Set(rows.map((r) => r.name));
  } catch (error) {
    console.error('db-migrate-remote: d1_migrations returned unparseable output; refusing to guess.');
    process.exit(1);
  }
} else {
  // Only a genuinely missing table means "fresh database". Anything else — an
  // auth blip, a network error — must abort: assuming empty here would replay
  // CREATE TABLE over a populated production database.
  const err = `${probe.stdout ?? ''}${probe.stderr ?? ''}`;
  if (/no such table: ?d1_migrations/i.test(err)) {
    console.log('db-migrate-remote: no d1_migrations table — treating as a fresh database.');
  } else {
    console.error('db-migrate-remote: could not read d1_migrations. Aborting rather than risk replaying migrations.');
    console.error(err.slice(0, 600));
    process.exit(1);
  }
}

const pending = all.filter((f) => !applied.has(f));
if (!pending.length) {
  console.log(`db-migrate-remote: nothing to do — all ${all.length} migrations already applied.`);
  process.exit(0);
}

let sql = '-- Generated by scripts/db-migrate-remote.mjs. Do not edit.\n';
sql += 'CREATE TABLE IF NOT EXISTS d1_migrations (\n';
sql += '  id INTEGER PRIMARY KEY AUTOINCREMENT,\n';
sql += '  name TEXT UNIQUE,\n';
sql += "  applied_at TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now'))\n";
sql += ');\n\n';
for (const file of pending) {
  const body = readFileSync(join(migrationsDir, file), 'utf8').replace(/-->\s*statement-breakpoint/g, '');
  sql += `-- ${file}\n${body.trim()}\n\n`;
}
for (const file of pending) {
  sql += `INSERT OR IGNORE INTO d1_migrations (name) VALUES ('${file}');\n`;
}
writeFileSync(pendingPath, sql);

console.log(`db-migrate-remote: applying ${pending.length} pending migration(s):`);
for (const file of pending) console.log(`  - ${file}`);

const res = wrangler(['d1', 'execute', cfg.d1_database_name, '--remote', '--file=.wrangler-pending.sql']);
try { rmSync(pendingPath); } catch {}
process.exit(res.status ?? 1);
